/**
 * 답변을 소리 내어 말했을 때 걸리는 시간 추정 (2026-08-07).
 *
 * ## 왜 필요한가
 *
 * 면접 답변은 **글자수보다 말하는 시간**이 실제 제약이다. 신입 면접은 1인 평균 26분에
 * 질문이 5개 안팎이라 답변 하나에 쓸 수 있는 시간이 1분 남짓이다. 글자수 카운터만
 * 보면 "5000자 중 800자" 라 여유로워 보이지만, 800자는 소리 내면 2분이 넘는다.
 *
 * ## 기준: 350 CPM (분당 글자수, **공백 포함**)
 *
 * 발표 속도 통용 기준에서 350~400 CPM 이 "또박또박 설명하는 발표" 다. 교차 검증도 맞는다 —
 * 널리 쓰이는 "1분 자기소개 원고는 350자" 관용과 정확히 일치한다 (350 ÷ 350 × 60 = 60초).
 *
 * 🔴 **공백을 빼면 안 된다** (2026-08-07 수정). 위 기준들은 전부 **공백 포함 글자수**로
 * 센 값이다. 공백을 빼고 350 으로 나누면 한국어 기준 약 23%가 사라져 **실제보다 짧게**
 * 나온다. 실제로 자기소개 답변 6건이 78~90초인데 58~68초로 표시되고 있었다 —
 * "1분 안쪽" 으로 보이니 사용자가 줄일 이유를 못 느낀다. 길이 경고 기능이 정반대로 작동했다.
 *
 * 다만 **연속 공백·줄바꿈은 1자로 접는다.** 원래 공백을 뺀 이유가 "줄바꿈 많은 메모가
 * 부풀어 보인다" 였는데, 그건 연속 공백만 접으면 해결된다.
 *
 * 🔴 **추정치다.** 사람마다 편차가 크므로 화면에서도 "약" 을 붙여 단정하지 않는다.
 */
export const CHARS_PER_MINUTE = 350

/** 면접 답변 1개의 통상 상한 (초). 넘으면 화면에서 주의색으로 알린다 */
export const ANSWER_LONG_SECONDS = 90

/**
 * 말하는 데 걸리는 시간(초).
 *
 * 공백은 **센다** (기준 CPM 이 공백 포함이므로). 다만 연속 공백·줄바꿈은 1자로 접어,
 * 줄바꿈을 많이 쓴 메모가 실제보다 길게 나오지 않게 한다.
 */
export function estimateSpeakingSeconds(text: string): number {
  const chars = text.trim().replace(/\s+/g, ' ').length
  if (chars === 0) return 0
  return Math.round((chars / CHARS_PER_MINUTE) * 60)
}

/** `1분 12초` · `48초` 형태. 0초면 빈 문자열 (표시하지 않는다) */
export function formatSpeakingTime(seconds: number): string {
  if (seconds <= 0) return ''
  if (seconds < 60) return `${seconds}초`
  const m = Math.floor(seconds / 60)
  const s = seconds % 60
  return s === 0 ? `${m}분` : `${m}분 ${s}초`
}
