/**
 * 시/도 이름을 백엔드가 받는 **짧은 이름 17개** 중 하나로 정규화한다. 못 맞추면 `null`.
 *
 * `null` 을 돌려주는 게 중요하다 — 모르는 값을 그대로 저장하면 백엔드가 400 을 주고,
 * 통과하더라도 통계 차원이 오염된다. 호출 측은 `null` 이면 사용자가 직접 고르게 둔다.
 */
export function normalizeRegion(raw: string | null | undefined): KoreaRegion | null {
  if (!raw) return null
  const s = raw.trim()
  if (!s) return null
  if ((KOREA_REGIONS as readonly string[]).includes(s)) return s as KoreaRegion
  return ALIASES[s] ?? null
}
