export interface TourCoverletterCopy {
  /** 문항 1 (펼쳐서 재생) */
  q1: string
  /** AI 초안 3줄 — 줄당 0.5s 로 타이핑된다 */
  draft1: [string, string, string]
  /** 「점검」 배지 3개 — 글자수 · 회사 키워드 · 두괄식 */
  checks: [string, string, string]
  /** 문항 1이 접힐 때 남는 한 줄 */
  summary1: string
  /** 문항 2 (짧게 재생) */
  q2: string
  draft2: [string, string]
}

export interface TourInterviewCopy {
  q1: string
  /** 답변 2줄 — 타이머가 도는 동안 채워진다 */
  answer1: [string, string]
  q2: string
  /** AI 피드백 말풍선 2줄 */
  feedback: [string, string]
}

export interface TourNoteCopy {
  /** `{step}` 치환 — 카드의 실제 면접 스텝과 이어진다 */
  title: string
  checklist: [string, string, string, string]
  imageLabel: string
}

export interface TourCopy {
  /** 계열 대표 직무 — `{job}` 의 기본값 */
  job: string
  coverletter: TourCoverletterCopy
  interview: TourInterviewCopy
  note: TourNoteCopy
}

