/**
 * 앱 소개 투어의 **계열별 내용 사전** (v2).
 *
 * ## ⚠️ v3 현재 **화면에서 쓰지 않는다** — 다음 회차 개인화 후보로 보존
 *
 * v2 는 이 사전으로 4·5·6장을 그 사람 계열에 맞춰 채웠다. 그런데 1장 카드(그 사람 회사)와
 * 사전 문장이 **서로 다른 이야기**를 해서 오히려 헷갈렸다 (CEO 2차 실기). v3 는 1~6장을
 * 무신사 · 브랜드 마케터 **한 이야기**로 통일했고(`showcase.ts`), 마지막 장에서만 내 카드로
 * 돌아온다.
 *
 * 🔴 **지우지 않는다.** 14계열 × 12항목을 다시 쓰는 비용이 크고, 「쇼케이스로 흐름을 이해시킨
 * 뒤 사용자 계열로 한 번 더」 같은 개인화가 다음 후보다. 테스트(`tourCopy.test.ts`)를 함께
 * 남겨 문장이 조용히 썩지 않게 한다.
 *
 * ---
 *
 * ## 왜 사전인가 (「예시」 라벨을 안 붙이려고)
 *
 * v1 은 「지원 동기를 말해 주세요」 같은 **껍데기 문장**을 보여줬다. 그러면 AI 를 **어떻게
 * 쓰는지**가 안 보이고, 화면이 「예시입니다」라고 변명해야 한다. v2 는 그 계열 사람이
 * **실제로 쓸 법한 문장**을 그대로 재생한다 — 읽고 나면 「내 것도 이렇게 되겠구나」가 남는다.
 *
 * 🔴 **AI 를 부르지 않는다.** 소개를 보여주려고 코인을 태울 수 없고, 실패하면 그 장면이
 * 통째로 비어버린다. 그래서 번들에 싣는다 (`seriesOnboarding` 이 같은 이유로 정적이다).
 *
 * ## 치환 토큰 3종
 *
 * | 토큰 | 값 | 없을 때 |
 * |---|---|---|
 * | `{company}` | 무대 회사명 | 무대가 항상 회사를 갖는다 (미리보기 포함) |
 * | `{job}` | 프로필·카드 직무 | **계열 대표 직무**(`job` 필드)로 떨어진다 |
 * | `{step}` | 카드의 실제 면접 스텝명 | `'1차 면접'` |
 *
 * 🔴 `{job}` 이 비었을 때 빈칸을 남기지 않으려고 계열마다 `job` 을 둔다 — 「 직무에
 * 지원한」처럼 조사만 남는 문장은 기계가 쓴 티가 그대로 난다.
 *
 * ## `SERIES_ONBOARDING` 과의 관계
 *
 * 저건 **온보딩 화면 전용**(계열 고른 직후 질문 3개)이라 건드리지 않는다. 투어 면접 장면은
 * 답변·피드백까지 재생해야 해서 질문만으로는 부족하고, 두 화면이 같은 질문을 반복하면
 * 「아까 본 것」이 된다.
 */
